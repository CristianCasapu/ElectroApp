/// Returnează toate localitățile ca liste de sugestii 'Localitate, Județ'.
List<String> getSugestiiLocalitati() {
  final result = <String>[];
  for (final entry in localitatiPerJudet.entries) {
    for (final loc in entry.value) {
      result.add('$loc, ${entry.key}');
    }
  }
  result.sort();
  return result;
}

/// Extrage județul dintr-un string 'Localitate, Județ'.
String? getJudetDinSuggestie(String sugestie) {
  final parts = sugestie.split(', ');
  if (parts.length >= 2) return parts.last;
  return null;
}

/// Extrage localitatea dintr-un string 'Localitate, Județ'.
String getLocalitateaDinSuggestie(String sugestie) {
  final idx = sugestie.lastIndexOf(', ');
  if (idx > 0) return sugestie.substring(0, idx);
  return sugestie;
}
